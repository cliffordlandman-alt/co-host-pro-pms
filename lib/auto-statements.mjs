// Monthly automatic owner statements: what the run does for each owner on a given Dubai date. Pure, no database.
// Off unless the owner's "auto statements" setting is on (default off). From the 6th of a month, the previous
// month's statements are generated as drafts. Emailing needs all of: the owner has an email, the owner's
// "auto send" setting is on, OUTBOUND_DELIVERY=on, and an earlier automatic statement of this owner was approved in
// the app (sent or paid). So the first automatic month always waits for someone to approve it in the app.
export const AUTO_STATEMENT_DAY = 6;

export function previousMonth(today) {
  const [y, m] = today.slice(0, 7).split("-").map(Number);
  return m === 1 ? `${y - 1}-12` : `${y}-${String(m - 1).padStart(2, "0")}`;
}

/** owner: { id, email, autoStatements, autoSend }; statements: this owner's statements { month, status, autoGeneratedAt }. */
export function autoStatementDecision({ today, owner, statements = [], outbound = false, lastRunMonth = null }) {
  const month = previousMonth(today);
  if (!owner?.autoStatements) return { run: false, month, reason: "Automatic statements are off for this owner" };
  if (Number(today.slice(8, 10)) < AUTO_STATEMENT_DAY) return { run: false, month, reason: `Runs from the ${AUTO_STATEMENT_DAY}th of the month` };
  if (lastRunMonth === month) return { run: false, month, reason: `Already ran for ${month}` };
  const approvedBefore = statements.some(s => s.autoGeneratedAt && s.month < month && (s.status === "sent" || s.status === "paid"));
  const blockers = [];
  if (!owner.email) blockers.push("the owner has no email address");
  if (!owner.autoSend) blockers.push("auto-send is off for this owner");
  if (!outbound) blockers.push("outgoing messages are switched off on this system (OUTBOUND_DELIVERY)");
  if (!approvedBefore) blockers.push("the first automatic month waits for approval in the app");
  return { run: true, month, send: blockers.length === 0, waitReason: blockers.length ? `Waiting for approval: ${blockers.join("; ")}` : null };
}
