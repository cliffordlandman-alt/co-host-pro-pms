import assert from 'node:assert/strict';
import { makeToday, mainPhoto } from '../artifacts/yallastay/src/lib/today-model.ts';
const day='2026-09-30';const property={id:1,name:'Sample property',status:'active',photos:'["/sample.jpg"]'};
const base=makeToday([property],[],[],[],day);
assert.equal(base.readiness[0].status,'NOT READY');assert.equal(base.timeline.length,0);
const approved={id:1,propertyId:1,status:'approved',scheduledDate:day,scheduledTime:'11:00'};
assert.equal(makeToday([property],[],[approved],[],day).readiness[0].status,'READY');
assert.equal(makeToday([property],[],[{...approved,status:'completed'}],[],day).readiness[0].status,'INSPECTION');
assert.equal(makeToday([property],[],[{...approved,status:'in_progress'}],[],day).readiness[0].status,'CLEANING');
const guest={id:2,propertyId:1,guestName:'Sample guest',checkIn:'2026-09-29',checkOut:'2026-10-01',status:'checked_in'};
assert.equal(makeToday([property],[guest],[approved],[],day).readiness[0].status,'OCCUPIED');
const issue={id:3,propertyId:1,status:'reported',priority:'high'};
assert.equal(makeToday([property],[guest],[approved],[issue],day).readiness[0].status,'MAINTENANCE');
const departure={...guest,status:'checked_out',checkOut:day};
assert.equal(makeToday([property],[departure],[{...approved,scheduledDate:'2026-09-28'}],[],day).readiness[0].status,'NOT READY');
const arrival={...guest,id:4,checkIn:day,status:'confirmed'};
const model=makeToday([property],[departure,arrival],[approved],[],day);
assert.equal(model.arrivals.length,1);assert.equal(model.departures.length,1);assert.equal(model.completed,2);assert.equal(model.timeline.length,3);
assert.equal(model.timeline.find(t=>t.type==='arrival').time,null);
assert.equal(makeToday([property],[{...arrival,status:'cancelled'}],[],[],day).arrivals.length,0);
assert.equal(mainPhoto(property),'/sample.jpg');assert.equal(mainPhoto({photos:'invalid'}),null);
console.log('PASS: readiness requires evidence, inspection stays distinct, occupancy/maintenance precedence, stale approvals rejected, actual timeline dates/times, progress, cancellations, safe photos.');
