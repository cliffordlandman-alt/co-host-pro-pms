// Build lib/yalla-master-template.mjs from the master workbook (YALLA_Financial_Report_with_Forecast.xlsm): every
// part (styles, theme, sheet XML with its styled cells, merges, conditional formats, validations, drawings, charts)
// is kept as the export's template; the export only writes data cells into it (lib/xlsx-template.mjs).
// Usage: node scripts/make-yalla-template.mjs /workspace/finance/YALLA_Financial_Report_with_Forecast.xlsm
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { unzipParts } from '../lib/xlsx-template.mjs';
const src = process.argv[2];
if (!src) { console.error('usage: make-yalla-template.mjs <master.xlsm>'); process.exit(2); }
const buf = fs.readFileSync(src), sha = crypto.createHash('sha256').update(buf).digest('hex');
const parts = unzipParts(buf);
if (parts['xl/vbaProject.bin']) delete parts['xl/vbaProject.bin'];
const text = Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, v.toString('utf8')]));
const b64 = gzipSync(Buffer.from(JSON.stringify(text)), { level: 9 }).toString('base64');
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../lib/yalla-master-template.mjs');
fs.writeFileSync(out, `// Generated by scripts/make-yalla-template.mjs from ${path.basename(src)} (sha256 ${sha}). Do not edit.\n` +
  `export const MASTER_SHA256 = '${sha}';\nexport const MASTER_FILE = '${path.basename(src)}';\nexport const TEMPLATE_GZ_B64 = [\n'${b64.match(/.{1,120}/g).join("',\n'")}',\n].join('');\n`);
console.log(`wrote ${out}: ${Object.keys(text).length} parts, ${b64.length} base64 chars, master sha256 ${sha}`);
